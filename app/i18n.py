def tr(key, lang='ru', **values):
    pair = MESSAGES[key]
    return pair[1 if lang == 'kk' else 0].format(**values)


def language(state, text='', explicit=None):
    if explicit in {'ru', 'kk'}:
        state['language'] = explicit
        state['language_auto'] = False
    elif state.get('language_auto', True) and re.search(r'[әғқңөұүһі]|\b(сәлем|рахмет|керек|бар ма)\b', text.lower()):
        state['language'] = 'kk'
    return state.setdefault('language', 'ru')


def search_phrase(text):
    result = text
    for kk, ru in [('автоматты ажыратқыш', 'автомат'), ('қалқан', 'щит'), ('қорап', 'коробка'),
                   ('сым', 'провод'), ('шам', 'лампа'), ('розетка', 'розетка'), ('арзан', 'дешевле'),
                   ('үш полюсті', '3P'), ('бір полюсті', '1P'), ('ампер', 'А')]:
        result = re.sub(kk, ru, result, flags=re.I)
    result = re.sub(r'\b(маған|керек|қажет|бар ма|табыңыз|тауып бер|ізде)\b', ' ', result, flags=re.I)
    return result.strip()


def localize_result(result, lang):
    result['language'] = lang
    if result.get('action') in MESSAGES and lang == 'kk':
        result['message'] = tr(result['action'], lang)
    if lang != 'kk':
        return result
    if result.get('warnings'):
        result['source_warnings'] = result['warnings']
        result['warnings'] = [tr('uncertain', lang)]
    for product in result.get('products', []):
        if not product.get('reason_is_grounded'):
            product['reason'] = 'Сұрауға сәйкес каталогтан табылды. Толық үйлесімділікті маманмен нақтылаңыз.'
        if product.get('warnings'):
            product['source_warnings'] = product['warnings']
            product['warnings'] = [tr('uncertain', lang)]
        product['certificate_status'] = 'Сертификат сілтемесі бар' if product.get('certificate') else 'API-де сертификат көрсетілмеген'
    result['clarification_questions'] = ['Жабдықтың негізгі параметрлерін және қолдану шарттарын нақтылаңыз.'] if result.get('clarification_questions') else []
    return result
